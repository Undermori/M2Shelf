const resources: Record<AppLanguage, Messages> = {
  "zh-CN": zhCN,
  "en-US": enUS,
  "ja-JP": jaJP,
  "ko-KR": koKR,
};

let activeLanguage: AppLanguage = "zh-CN";

function interpolate(template: string, values?: Values): string {
  if (!values) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) =>
    Object.prototype.hasOwnProperty.call(values, key) ? String(values[key]) : match,
  );
}

export function translate(language: AppLanguage, key: MessageKey, values?: Values): string {
  return interpolate(resources[language][key] ?? zhCN[key], values);
}

export function translateActive(key: MessageKey, values?: Values): string {
  return translate(activeLanguage, key, values);
}

export function getActiveLanguage(): AppLanguage {
  return activeLanguage;
}

interface I18nValue {
  language: AppLanguage;
  setLanguage: (language: AppLanguage) => void;
  t: (key: MessageKey, values?: Values) => string;
  number: (value: number) => string;
}

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [language, setLanguageState] = useState<AppLanguage>("zh-CN");
  const setLanguage = useCallback((next: AppLanguage) => {
    activeLanguage = next;
    setLanguageState(next);
  }, []);
  useEffect(() => {
    activeLanguage = language;
    document.documentElement.lang = language;
  }, [language]);
  const value = useMemo<I18nValue>(() => ({
    language,
    setLanguage,
    t: (key, values) => translate(language, key, values),
    number: (numberValue) => numberValue.toLocaleString(language),
  }), [language, setLanguage]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n(): I18nValue {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}

export type { MessageKey };
